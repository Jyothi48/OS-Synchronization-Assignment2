READERS = 3
WRITERS = 2
condition = threading.Condition()
active_readers = 0
active_writer = False
waiting_writers = 0
states = {f"Reader {i}": "Waiting" for i in range(1, READERS+1)}
states.update({f"Writer {i}": "Waiting" for i in range(1, WRITERS+1)})


def reader(i):
    global active_readers
    time.sleep(random.uniform(0.02, 0.18))
    with condition:
        while active_writer or waiting_writers > 0:
            states[f"Reader {i}"] = "Waiting on monitor condition"
            record(f"Reader {i} waits because a writer is active or queued.", states)
            condition.wait()
        active_readers += 1
        states[f"Reader {i}"] = "Reading"
        record(f"Reader {i} enters the reading section (active readers: {active_readers}).", states)
    time.sleep(random.uniform(0.08, 0.18))
    with condition:
        active_readers -= 1
        states[f"Reader {i}"] = "Finished reading"
        record(f"Reader {i} leaves the reading section (active readers: {active_readers}).", states)
        if active_readers == 0:
            condition.notify_all()


def writer(i):
    global active_writer, waiting_writers
    time.sleep(random.uniform(0.01, 0.16))
    with condition:
        waiting_writers += 1
        states[f"Writer {i}"] = "Waiting on monitor condition"
        record(f"Writer {i} requests exclusive access.", states)
        while active_writer or active_readers > 0:
            condition.wait()
        waiting_writers -= 1
        active_writer = True
        states[f"Writer {i}"] = "Writing"
        record(f"Writer {i} enters the writing section exclusively.", states)
    time.sleep(random.uniform(0.08, 0.16))
    with condition:
        active_writer = False
        states[f"Writer {i}"] = "Finished writing"
        record(f"Writer {i} exits the writing section.", states)
        condition.notify_all()


if __name__ == "__main__":
    random.seed(11)
    record("Simulation started; monitor is ready.", states)
    threads = [threading.Thread(target=reader, args=(i,)) for i in range(1, READERS+1)] + [threading.Thread(target=writer, args=(i,)) for i in range(1, WRITERS+1)]
    random.shuffle(threads)
    for t in threads: t.start()
    for t in threads: t.join()
    record("All reader and writer threads have completed.", states)
    write_html("Readers–Writers: Monitor Solution", list(states), "A monitor is represented by a Condition that protects shared state. Readers wait while a writer is active or waiting; writers wait until no reader or writer is active. This reduces writer starvation, though scheduling fairness still depends on the runtime.")
